clients = pd.DataFrame({
    "ID": [1,2,3,4,5],
    "Ім'я": ["Іван","Петро","Оля","Анна","Макс"],
    "Місто": ["Львів","Київ","Одеса","Львів","Харків"]
})

orders2 = pd.DataFrame({
    "ID клієнта": [1,2,1,3,5],
    "Замовлення": ["A","B","C","D","E"],
    "Вартість": [100,200,150,300,250]
})

print(clients)
print(orders2)

merged = pd.merge(clients, orders2, left_on="ID", right_on="ID клієнта")
print("Об'єднано:\n", merged)

result = merged.groupby("Ім'я")["Вартість"].sum().reset_index()
print("Сума по клієнтах:\n", result)